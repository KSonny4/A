import Foundation

public enum ClipKind: String, Codable, CaseIterable, Sendable {
    case text, link, image, file, color, other

    public var displayName: String {
        switch self {
        case .text: return "Text"
        case .link: return "Link"
        case .image: return "Image"
        case .file: return "File"
        case .color: return "Color"
        case .other: return "Other"
        }
    }
}

/// One type → data pair from a pasteboard item.
public struct ClipRepresentation: Equatable, Sendable {
    public var type: String
    public var data: Data

    public init(type: String, data: Data) {
        self.type = type
        self.data = data
    }
}

/// Everything that was on the pasteboard: one entry per pasteboard item, each with all its representations.
public struct ClipPayload: Equatable, Sendable {
    public var items: [[ClipRepresentation]]

    public init(items: [[ClipRepresentation]]) {
        self.items = items
    }

    public var byteSize: Int { items.reduce(0) { $0 + $1.reduce(0) { $0 + $1.data.count } } }

    public func firstData(ofTypes types: [String]) -> (type: String, data: Data)? {
        for item in items {
            for type in types {
                if let rep = item.first(where: { $0.type == type }) { return (rep.type, rep.data) }
            }
        }
        return nil
    }
}

public struct ClipMeta: Codable, Equatable, Sendable {
    public var imageWidth: Int?
    public var imageHeight: Int?
    public var filePaths: [String]?
    public var colorHex: String?
    public var url: String?
    public var wordCount: Int?
    public var types: [String]?

    public init(imageWidth: Int? = nil, imageHeight: Int? = nil, filePaths: [String]? = nil,
                colorHex: String? = nil, url: String? = nil, wordCount: Int? = nil, types: [String]? = nil) {
        self.imageWidth = imageWidth
        self.imageHeight = imageHeight
        self.filePaths = filePaths
        self.colorHex = colorHex
        self.url = url
        self.wordCount = wordCount
        self.types = types
    }
}

/// A row of clipboard history as shown in lists (without the heavy payload).
public struct ClipRecord: Identifiable, Hashable, Sendable {
    public let id: Int64
    public var kind: ClipKind
    public var preview: String
    public var charCount: Int
    public var byteSize: Int
    public var sourceBundleID: String?
    public var sourceAppName: String?
    public var meta: ClipMeta
    public var createdAt: Date
    public var lastCopiedAt: Date
    public var copyCount: Int
    public var pinned: Bool

    public static func == (lhs: ClipRecord, rhs: ClipRecord) -> Bool {
        lhs.id == rhs.id && lhs.lastCopiedAt == rhs.lastCopiedAt && lhs.pinned == rhs.pinned && lhs.copyCount == rhs.copyCount
    }

    public func hash(into hasher: inout Hasher) {
        hasher.combine(id)
    }

    /// Single-line title like Raycast's list rows.
    public var title: String {
        switch kind {
        case .file:
            let names = (meta.filePaths ?? []).map { ($0 as NSString).lastPathComponent }
            if names.count > 1 { return "\(names[0]) and \(names.count - 1) more" }
            return names.first ?? preview
        case .image:
            if let w = meta.imageWidth, let h = meta.imageHeight { return "Image (\(w)×\(h))" }
            return "Image"
        case .other:
            return preview.isEmpty ? "Clipboard item" : preview
        default:
            let line = preview
                .split(whereSeparator: \.isNewline)
                .lazy
                .map { $0.trimmingCharacters(in: .whitespaces) }
                .first(where: { !$0.isEmpty }) ?? ""
            return line.isEmpty ? "(whitespace)" : String(line.prefix(300))
        }
    }
}

/// Pasteboard types that indicate the content should not be recorded (password managers etc.).
public enum PasteboardMarkers {
    public static let skip: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Promised/lazy types that are expensive or meaningless to read back.
    public static let excludedTypes: Set<String> = [
        "com.apple.pasteboard.promised-file-content-type",
        "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-suggested-file-name",
        "com.apple.NSFilePromiseItemMetaData",
        "NSPromiseContentsPboardType",
    ]

    public static let plainText = "public.utf8-plain-text"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"
    public static let imageTypes = ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif", "com.adobe.pdf"]
    public static let color = "com.apple.cocoa.pasteboard.color"
}
